import fs from 'node:fs/promises';
import {realpathSync} from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const run=path.resolve(process.argv[2]||'output/dynamic-remediation/20260926-r01');
const repo=path.join(run,'reference/spine-runtimes-4.0');
const commit=execFileSync('git',['rev-parse','HEAD'],{cwd:repo,encoding:'utf8'}).trim();
if(commit!=='425ce416bb218b28caeec47b317aa57cd7140375')throw Error('Unexpected official source revision');
if(execFileSync('git',['status','--porcelain'],{cwd:repo,encoding:'utf8'}).trim())throw Error('Official source checkout must be unmodified');
const esbuild=createRequire(realpathSync('apps/core/node_modules/vite/package.json'))('esbuild');
const outfile=path.join(run,'reference/spine-webgl-4.0.official.js');
const options={entryPoints:[path.join(repo,'spine-ts/spine-webgl/src/index.ts')],alias:{'@esotericsoftware/spine-core':path.join(repo,'spine-ts/spine-core/src/index.ts')},bundle:true,format:'iife',globalName:'spine',outfile,legalComments:'inline',minify:false};
await esbuild.build(options);
const sha256=createHash('sha256').update(await fs.readFile(outfile)).digest('hex');
const provenance={upstream:'https://github.com/EsotericSoftware/spine-runtimes',commit,source:'spine-ts/spine-webgl/src/index.ts',sha256,build:{tool:'esbuild',version:esbuild.version,options},unmodifiedUpstream:true,purpose:'Independent diagnostic reference; not installed as production runtime'};
await fs.writeFile(outfile+'.provenance.json',JSON.stringify(provenance,null,2));
console.log(JSON.stringify(provenance));
