// Extract literal data only; never execute the legacy extension or its plugins.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import ts from 'typescript';
const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'temp/三国杀·琉璃版5.5/resources/app/extension/千幻聆音');
const media = path.join(root, 'apps/core/extension/ui/手杀标准UI/original/千幻聆音');
const destination = path.join(root, 'apps/core/noname/skin/qianhuan');
const shareFile = path.join(source, 'skinShare.js');
const tree = ts.createSourceFile(shareFile, fs.readFileSync(shareFile, 'utf8'), ts.ScriptTarget.Latest, true);
function literal(node) {
 if (ts.isStringLiteral(node) || ts.isNumericLiteral(node)) return node.text;
 if (ts.isObjectLiteralExpression(node)) return Object.fromEntries(node.properties.map(property => {
  if (!ts.isPropertyAssignment(property)) throw Error('Nonliteral skin sharing property');
  return [property.name.text, literal(property.initializer)];
 }));
 throw Error('Nonliteral skin sharing data');
}
let sharing;
function visit(node) {
 if (ts.isBinaryExpression(node) && node.left.getText(tree) === 'lib.qhly_skinShare') sharing = literal(node.right);
 ts.forEachChild(node, visit);
}
visit(tree);
if (!sharing) throw Error('Missing original skin sharing table');
const skins = {};
const skinRoot = path.join(media, 'sanguoskin');
for (const dir of fs.readdirSync(skinRoot, {withFileTypes:true}).filter(entry=>entry.isDirectory()).sort((a,b)=>a.name.localeCompare(b.name))) {
 const names = fs.readdirSync(path.join(skinRoot, dir.name)).sort();
 const atlases = new Set(names.filter(name=>/\.(atlas|skel)$/i.test(name)).map(name=>name.replace(/\.[^.]+$/,'').toLowerCase()));
 const images = names.filter(name=>/\.(png|jpe?g|webp|avif|gif)$/i.test(name) && !atlases.has(name.replace(/\.[^.]+$/,'').toLowerCase()));
 if (images.length) skins[dir.name] = images;
}
const hashes = Object.fromEntries(['extension.js','theme/shousha/code/shousha.js','skinShare.js'].map(file=>[file,crypto.createHash('sha256').update(fs.readFileSync(path.join(source,file))).digest('hex')]));
fs.mkdirSync(destination, {recursive:true});
fs.writeFileSync(path.join(destination,'catalog-data.js'), '// Generated by scripts/migrate-qianhuan-static.mjs; literal source data only.\nexport const skinFiles = '+JSON.stringify(skins,null,2)+';\nexport const skinSharing = '+JSON.stringify(Object.fromEntries(Object.entries(sharing).map(([key,value])=>[key,value.name])),null,2)+';\n');
fs.writeFileSync(path.join(destination,'SOURCE.json'), JSON.stringify({name:'千幻聆音',author:'玄武江湖工作室 & 雷',version:'4.13.8.1',source:'temp/三国杀·琉璃版5.5/resources/app/extension/千幻聆音',hashes,credits:'原作者说明保留在素材目录 readme.md；遵循项目 GPL-3.0-only，素材归属原作者。',migration:{model:'shousha.js skin.getCurrentSkin / refreshAfterGot / refresh skin list; extension.js qhly_getSkinName',view:'Adapted shousha big portrait, horizontal skin cards, classic first and explicit apply; core adapter replaces global qhly calls.',excluded:['prototype overrides','player initialization','plugins','dynamic rendering','audio replacement']},characters:Object.keys(skins).length,images:Object.values(skins).reduce((n,files)=>n+files.length,0)},null,2)+'\n');
console.log(`Qianhuan static catalogue: ${Object.keys(skins).length} characters, ${Object.values(skins).reduce((n,files)=>n+files.length,0)} images.`);
